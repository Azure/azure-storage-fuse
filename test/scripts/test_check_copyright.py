import contextlib
import io
import subprocess
import tempfile
import unittest
from pathlib import Path

from check_copyright import check_repository, has_header


GO_HEADER = (
    "// Copyright (c) Microsoft Corporation.\n"
    "// Licensed under the MIT License.\n"
)
C_HEADER = (
    "/*\n"
    " * Copyright (c) Microsoft Corporation.\n"
    " * Licensed under the MIT License\n"
    " */\n"
)


class CopyrightCheckTest(unittest.TestCase):
    def test_accepts_headers_with_build_tags_and_line_endings(self):
        samples = [
            (".go", GO_HEADER + "\npackage example\n"),
            (".go", "//go:build unittest\n// +build unittest\n\n" + GO_HEADER),
            (".go", GO_HEADER + "\n// Code generated by MockGen. DO NOT EDIT.\n"),
            (".template", GO_HEADER + "\npackage <component>\n"),
            (".c", C_HEADER + "\nint main(void) { return 0; }\n"),
            (".h", "\n" + C_HEADER.replace("\n", "\r\n") + "\n#ifndef EXAMPLE\n"),
        ]
        for suffix, text in samples:
            with self.subTest(suffix=suffix, text=text):
                self.assertTrue(has_header(text, suffix))

    def test_rejects_missing_incorrect_or_misplaced_headers(self):
        samples = [
            (".go", "// Copyright (c) Microsoft Corporation.\n"),
            (".go", GO_HEADER.replace("Microsoft", "Other")),
            (".go", GO_HEADER.replace("MIT License.", "MIT License. extra")),
            (".go", "package example\n\n" + GO_HEADER),
            (".go", C_HEADER),
            (".c", GO_HEADER),
            (".c", C_HEADER.replace("/*\n", "/**\n")),
            (".h", C_HEADER.replace("MIT License", "Apache License")),
            (".template", "\npackage <component>\n"),
        ]
        for suffix, text in samples:
            with self.subTest(suffix=suffix, text=text):
                self.assertFalse(has_header(text, suffix))

    def test_checks_tracked_files_and_reports_each_failure(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            subprocess.run(["git", "init", "-q", str(root)], check=True)
            fixtures = {
                "valid.go": GO_HEADER + "\npackage example\n",
                "invalid name.c": "int main(void) { return 0; }\n",
                "invalid.h": GO_HEADER,
                "internal/component.template": "package <component>\n",
                "notes.txt": "not a source file\n",
            }
            for name, text in fixtures.items():
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
            subprocess.run(["git", "-C", str(root), "add", "--", *fixtures], check=True)
            (root / "scratch.go").write_text("package scratch\n", encoding="utf-8")

            errors = io.StringIO()
            with contextlib.redirect_stderr(errors):
                self.assertEqual(check_repository(root), 1)
            for name in ("invalid name.c", "invalid.h", "internal/component.template"):
                self.assertIn(f"{name}: missing or incorrect", errors.getvalue())
            self.assertNotIn("scratch.go", errors.getvalue())
            self.assertNotIn("notes.txt", errors.getvalue())

            (root / "invalid name.c").write_text(C_HEADER, encoding="utf-8")
            (root / "invalid.h").write_text(C_HEADER, encoding="utf-8")
            (root / "internal/component.template").write_text(GO_HEADER, encoding="utf-8")
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(check_repository(root), 0)


if __name__ == "__main__":
    unittest.main()
